import struct
import os

def rle_encode(bmp_path):
    with open(bmp_path, "rb") as f:
        data = f.read()[54:]
    pixels = [struct.unpack("<I", data[i:i+4])[0] for i in range(0, len(data), 4)]
    runs = []
    cur_p = pixels[0]
    cur_len = 0
    for p in pixels:
        if p == cur_p and cur_len < 65535:
            cur_len += 1
        else:
            runs.append((cur_p, cur_len))
            cur_p = p
            cur_len = 1
    runs.append((cur_p, cur_len))
    return runs

